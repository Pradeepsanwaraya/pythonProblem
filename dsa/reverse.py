class Solution(object):
    def connect(self, root):
        if not root:
            return root

        queue = [root]

        while queue:
            size = len(queue)

            for i in range(size):
                node = queue.pop(0)

                if i < size - 1:
                    node.next = queue[0] if queue else None

                if node.left:
                    queue.append(node.left)

                if node.right:
                    queue.append(node.right)

        return root

